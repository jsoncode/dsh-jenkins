/** 当前语言的词典（每次调用解析 —— 语言切换后即刻生效，无需重建模块状态）。 */
const dictOf = () => (COPY[lang] || COPY.zh);
/** 取文案并替换 {var} 占位符。 */
export const t = (key, vars) => {
    const dict = dictOf();
    let s = dict[key] !== undefined ? dict[key] : String(key);
    if (vars) {
        for (const k of Object.keys(vars)) {
            s = s.split('{' + k + '}').join(String(vars[k]));
        }
    }
    return s;
};
/** 宿主错误通过 code 映射为本地化文本，未知错误回退原文。 */
export const tErr = (res, fallback) => {
    const dict = dictOf();
    if (res && res.code) {
        const local = dict.errors[res.code];
        if (local !== undefined) {
            const zh = lang === 'zh';
            const sep = zh ? '：' : ': ';
            if (res.code === 'trigger-http') {
                return t('triggerFailed') + (zh ? '（HTTP ' : ' (HTTP ') + res.status + (zh ? '）：' : '): ') + (res.detail || '');
            }
            if (res.code === 'network-failed') {
                // 附带 curl 的真实报错（DNS/连接/TLS/超时等），便于排查
                const detail = res.error ? String(res.error).replace(/^(网络请求失败|Network request failed)[:：]\s*/, '').trim() : '';
                return local + (detail ? (zh ? '：' : ': ') + detail : '');
            }
            if (res.code === 'template-save-failed') {
                // 附带宿主 fs 的真实报错（沙箱拒绝 / 路径 / 权限等），便于排查
                const detail = res.error ? String(res.error).trim() : '';
                return local + (detail ? (zh ? '：' : ': ') + detail : '');
            }
            return local;
        }
    }
    return (res && res.error) || fallback || '';
};
/** 时长格式化（配合 t('sec'/'min'/'hour')）。 */
export const fmtDur = (ms) => {
    if (!ms || ms < 0)
        return '—';
    const s = Math.floor(ms / 1000);
    if (s < 60)
        return s + t('sec');
    const m = Math.floor(s / 60);
    if (m < 60)
        return m + t('min') + (s % 60) + t('sec');
    const h = Math.floor(m / 60);
    return h + t('hour') + (m % 60) + t('min');
};
